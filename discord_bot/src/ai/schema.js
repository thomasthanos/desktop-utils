/**
 * Τι επιτρέπεται να ζητήσει το μοντέλο.
 *
 * Τέσσερα επίπεδα, αλλά μόνο τα τρία πρώτα υπάρχουν σε αυτό το αρχείο:
 *
 *   0  κουβέντα                                  → `none`
 *   1  ανάγνωση: queue, nowplaying, stats, help   → άμεσα
 *   2  αναπαραγωγή: play, pause, skip, volume...  → άμεσα, ΜΟΝΟ αν περνάει ο
 *                                                   ίδιος έλεγχος που θα
 *                                                   περνούσε ο χρήστης με το χέρι
 *   3  clear, wipe-channel, addauthorized         → ΠΟΤΕ
 *
 * Το επίπεδο 3 **δεν υπάρχει καν ως τιμή** στο enum. Το μοντέλο δεν έχει token
 * για να το εκφράσει — δεν είναι φίλτρο που ελέγχει την έξοδο, είναι απουσία
 * της εξόδου. Ένα φίλτρο μπορεί να έχει κενό· ένα enum που δεν περιέχει τη λέξη
 * δεν μπορεί.
 *
 * ΔΕΝ μπαίνει κουμπί επιβεβαίωσης για τις καταστροφικές, για τρεις λόγους:
 *
 *   - Ένα κουμπί που εμφανίζεται σε κάθε «καθάρισε λίγο» εκπαιδεύει το
 *     αυτόματο «ναι». Ίδιο σκεπτικό με τον περιοριστή ρυθμού στο notify.js: ό,τι
 *     έρχεται συνέχεια, μαθαίνεις να το αγνοείς.
 *   - Το επικίνδυνο δεν είναι η κλήση, είναι οι ΠΑΡΑΜΕΤΡΟΙ. «Καθάρισε λίγο» →
 *     20 μηνύματα ή 7 μέρες; Εκατονταπλάσια διαφορά, κρυμμένη σε μια ετικέτα
 *     κουμπιού που θα προσπεράσεις.
 *   - Το /clear απέχει ένα slash και ελέγχεται ήδη από δικαιώματα. Το AI δεν
 *     προσθέτει καμία ευκολία εκεί, μόνο ρίσκο.
 *
 * Αντ' αυτού απαντάει με την ίδια την εντολή ως κείμενο, ώστε να βλέπεις τις
 * ακριβείς παραμέτρους στη σύνταξη που θα πληκτρολογούσες.
 */

/** Επίπεδο 1 — μόνο ανάγνωση. Δεν αλλάζουν τίποτα. */
const READ_ACTIONS = ['queue', 'nowplaying', 'stats', 'help'];

/** Επίπεδο 2 — αλλάζουν την αναπαραγωγή, ποτέ δεδομένα. */
const PLAYBACK_ACTIONS = ['play', 'pause', 'resume', 'skip', 'stop', 'volume', 'loop', 'stay247'];

/**
 * Επίπεδο 3 — ΔΕΝ ΜΠΑΙΝΟΥΝ ΠΟΤΕ στο enum.
 *
 * Υπάρχουν εδώ ως λίστα ώστε τα τεστ να μπορούν να βεβαιωθούν ότι απουσιάζουν.
 * Το να τα γράψεις κάπου είναι ο μόνος τρόπος να ελέγξεις ότι λείπουν από
 * αλλού.
 */
const FORBIDDEN_ACTIONS = [
  'clear', 'wipe-channel', 'wipe', 'purge', 'delete',
  'addauthorized', 'removeauthorized', 'ban', 'kick'
];

const ALLOWED_ACTIONS = ['none', ...READ_ACTIONS, ...PLAYBACK_ACTIONS];

/**
 * Σχήμα δομημένης εξόδου (Gemini responseSchema / OpenAI json_schema).
 */
function buildResponseSchema() {
  return {
    type: 'object',
    properties: {
      reply: {
        type: 'string',
        description: 'Η απάντηση προς τον χρήστη, στα ελληνικά, το πολύ 3 προτάσεις.'
      },
      action: {
        type: 'string',
        enum: ALLOWED_ACTIONS,
        description: 'Τι πρέπει να εκτελεστεί. "none" για απλή κουβέντα.'
      },
      query: {
        type: 'string',
        description: 'Για action="play": τι να παίξει. Αλλιώς κενό.'
      },
      value: {
        type: 'integer',
        description: 'Για action="volume": 0-100. Αλλιώς 0.'
      }
    },
    required: ['reply', 'action']
  };
}

